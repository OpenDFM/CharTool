def _extract_tool_calls(response: str):
    tool_call_regex = regex.compile(r"<tool_call>(.*?)</tool_call>", regex.DOTALL)
    matches = tool_call_regex.findall(response)
    function_calls = []
    for match in matches:
        try:
            function_call = json.loads(match)
            name, arguments = function_call["name"], function_call["arguments"]
            function_calls.append(dict(name=name, arguments=json.dumps(arguments, ensure_ascii=False)))
        except Exception as e:
            logger.error(f"Failed to decode tool call: {e}")
    
    return function_calls

def _build_tool_content(result: Dict[str, Any], tool_images: List[Dict[str, str]], url: bool = False) -> Any:
    text_content = f"Stdout:\n{result['stdout']}\nStderr:\n{result['stderr']}"

    if result["images"]:
        content_parts = []
        if result['stdout'] or result['stderr']:
            content_parts.append({"type": "text", "text": text_content})

        for img in result["images"]:
            tool_images.append(img)
            content_parts.append({
                "type": "image_url",
                "image_url": {
                    "url": f"data:image/png;base64,{img['base64']}",
                } if url else f"data:image/png;base64,{img['base64']}"
            })

        return content_parts

    return text_content

def extract_answer_from_cot(solution_str: str) -> tuple:
    """
    Extract answer from CoT (Chain of Thought) response.

    Returns:
        tuple: (answer_text, is_format_error)
    """
    # Initialize tracking variables
    is_format_error = False

    # 1. Check <think> tag format
    count_think_1 = solution_str.count("<think>")
    count_think_2 = solution_str.count("</think>")
    if count_think_1 != count_think_2:
        is_format_error = True

    # 2. Extract answer text - STRICT: only from <answer> tags
    answer_text = ""

    # Remove <think> section first
    predict_no_think = (
        solution_str.split("</think>")[-1].strip()
        if "</think>" in solution_str
        else solution_str.strip()
    )

    # Check <answer> tag format
    count_answer_1 = predict_no_think.count("<answer>")
    count_answer_2 = predict_no_think.count("</answer>")
    if count_answer_1 != count_answer_2:
        is_format_error = True

    # Try to extract from <answer> tags (STRICT - only this method)
    answer_match = regex.search(
        r"<answer>(.*?)</answer>", predict_no_think, regex.DOTALL
    )
    if answer_match:
        answer_text = answer_match.group(1).strip()
    else:
        # No proper <answer> tags found - this is a format error
        is_format_error = True
        answer_text = ""

    return answer_text, is_format_error

def generate_response(queries, model_path, max_tokens=2048):
    """
    Generate responses with code execution support (greedy decoding only).
    For pass@k experiments, use generate_response_with_code_executer_pass_k instead.
    """
    model = Qwen2_5_VLForConditionalGeneration.from_pretrained(
        model_path,
        torch_dtype=torch.bfloat16,
        attn_implementation="flash_attention_2",
        device_map="auto",
        trust_remote_code=True,
    )
    processor = AutoProcessor.from_pretrained(model_path, use_fast=True)
    sandbox = SandboxWrapper()

    for k in tqdm(queries):
        query = queries[k]["question"]
        image = queries[k]["figure_path"]
        image = r"file://" + image
        with open(queries[k]["figure_path"], "rb") as image_file:
            image_base64 = base64.b64encode(image_file.read()).decode("utf-8")

        messages = [
            {"role": "system", "content": system_message},
            {
                "role": "user",
                "content": [
                    {"type": "image", "image": image},
                    {"type": "text", "text": query},
                ],
            },
        ]

        text = processor.apply_chat_template(
            messages, tokenize=False, add_generation_prompt=True, tools=TOOLS
        )
        prompt_length = len(text)

        # Initialize conversation tracking
        code_num = 0
        final_stop_reason = None
        max_steps = 5

        tool_images = []
        step = 0

        while step < max_steps:
            step += 1
            logger.info(f"Step {step}/{max_steps}...")
            
            text = processor.apply_chat_template(
                messages, tokenize=False, add_generation_prompt=True, tools=TOOLS
            )
            image_inputs, video_inputs = process_vision_info(messages)
            inputs = processor(
                text=[text],
                images=image_inputs,
                videos=video_inputs,
                padding=True,
                return_tensors="pt",
            )
            inputs = inputs.to(model.device)
            with torch.no_grad():
                generated_ids = model.generate(
                    **inputs,
                    max_new_tokens=max_tokens,
                    do_sample=False,
                )
            generated_ids_trimmed = [
                out_ids[len(in_ids) :]
                for in_ids, out_ids in zip(inputs.input_ids, generated_ids)
            ]
            response = processor.batch_decode(
                generated_ids_trimmed, skip_special_tokens=True, clean_up_tokenization_spaces=False
            )[0]
            messages.append({"role": "assistant", "content": response})

            tool_calls = _extract_tool_calls(response)

            if tool_calls:
                code_num += len(tool_calls)

                for func in tool_calls:
                    func_name = func.get("name", "")
                    func_args = func.get("arguments", "{}")
                    if func_name == "python_interpreter":
                        try:
                            args = json.loads(func_args)
                            code = args.get("code", "")
                        except json.JSONDecodeError:
                            code = func_args

                        logger.debug("Executing Code...")
                        result = sandbox.execute(
                            code=code,
                            image_base64=image_base64,  # Can be extended to support image input
                            fetch_output_image=True,
                            timeout=10
                        )
                        tool_content = _build_tool_content(result, tool_images)

                        messages.append({
                            "role": "tool",
                            "name": "python_interpreter",
                            "content": tool_content
                        })
                    else:
                        logger.error(f"Unknown tool call: {func_name}")
                        continue
            else:
                break
        
        images_list = []
        SAVE_IMAGE_DIR.mkdir(parents=True, exist_ok=True)
        for idx, img in enumerate(tool_images):
            img_path = SAVE_IMAGE_DIR / f"{k}_{idx}.png"
            with open(img_path, "wb") as f:
                f.write(base64.b64decode(img['base64']))
            images_list.append(str(img_path))
        
        text = processor.apply_chat_template(
            messages, tokenize=False, add_generation_prompt=False, tools=TOOLS
        )
        final_response_text = text[prompt_length:]

        # Extract answer using extract_answer_from_cot
        extracted_answer, format_error = extract_answer_from_cot(final_response_text)

        # Store results
        queries[k]["response"] = final_response_text
        queries[k]["code_num"] = code_num
        queries[k]["stop_reasons"] = final_stop_reason
        queries[k]["extracted_answer"] = extracted_answer
        queries[k]["format_error"] = format_error
        queries[k]["tool_images"] = images_list  # Store all generated images
